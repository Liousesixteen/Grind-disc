def main():
    cfg = json.load(open(CFG_P, encoding="utf-8"))
    chains = cfg["chains"]

    old = chains.get("_题材直连") or {}
    merged = dict(old)
    added, skipped = [], []
    for t, loc in DIRECT.items():
        cn, _, sn = loc.partition("·")
        if cn not in chains:
            raise SystemExit(f"链不存在：{cn}（来自 {t}）")
        if sn and sn not in (chains[cn].get("环节") or {}):
            raise SystemExit(f"环节不存在：{loc}（来自 {t}）")
        if t in merged:
            skipped.append(f"{t}（已是 {merged[t]}）")
            continue
        merged[t] = loc
        added.append(f"{t} → {loc}")
    merged["_说明"] = NOTE["_说明"]
    merged["_准入"] = NOTE["_准入"]
    chains["_题材直连"] = merged

    g = cfg["granularity"]
    ex = g.get("exclude_words") or []
    added_ex = [w for w in NOISE if w not in ex]
    g["exclude_words"] = ex + added_ex
    g["_exclude_note_20261024"] = ("Step3 追加政策/地域/事件/指数类 21 个：它们横跨所有链、"
                                   "无独立资金行为（粒度判据 1），留在归因候选里只会把真题材挤掉——"
                                   "实测科远智慧的归因被『新型工业化』抢走，海洋王被『物联网』抢走。")

    json.dump(cfg, open(CFG_P, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"直连表：新增 {len(added)} 条，跳过 {len(skipped)} 条")
    for a in added:
        print("   ", a)
    for s in skipped:
        print("    （跳过）", s)
    print(f"exclude_words：追加 {len(added_ex)} 个 → {g['exclude_words'].__len__()} 个")


if __name__ == "__main__":
    main()
