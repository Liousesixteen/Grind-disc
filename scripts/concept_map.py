def _norm(s):
    return str(s or "").replace(" ", "")


_SEG_EXTRA_N = {}


_SEG_EXTRA_N.update({_norm(k): v for k, v in SEG_EXTRA.items()})


def classify(concept):
    """单概念 → {类目, 链, 环节, 主题域, 子类, 规则}。顺序＝产业优先，宽泛收编最后。"""
    c = _norm(concept)
    # ① 产业：现链词表
    ch, sg = P.chain_of(c, CFG["chains"])
    if ch:
        return {"类目": "产业题材", "链": ch, "环节": sg if not str(sg).startswith("（") else "",
                "主题域": "", "子类": "", "规则": "链词表"}
    # ② 产业长尾补充表（键先去空格，避免「WiFi 6」这类写法漏配）
    if c in _SEG_EXTRA_N:
        ch2, sg2 = _SEG_EXTRA_N[c]
        return {"类目": "产业题材", "链": ch2, "环节": sg2, "主题域": "", "子类": "", "规则": "长尾补表"}
    # ③ 平台生态
    for dom, names in PLATFORM.items():
        if c in names or (dom + "概念") == c:
            return {"类目": "平台生态", "链": "", "环节": "", "主题域": dom, "子类": "", "规则": "平台词表"}
    # ④ 地域
    if c in REGION:
        return {"类目": "地域区域", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "地域词表"}
    # ⑤ 政策
    if c in POLICY:
        return {"类目": "政策主题", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "政策词表"}
    # ⑥ 资金 / ⑦ 交易状态 / ⑧ 事件财务
    if c in MONEY:
        return {"类目": "资金持仓", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "资金词表"}
    if c in STYLE:
        return {"类目": "交易状态", "链": "", "环节": "", "主题域": "", "子类": "风格", "规则": "风格词表"}
    if c in INDEX:
        return {"类目": "交易状态", "链": "", "环节": "", "主题域": "", "子类": "指数成分", "规则": "指数表"}
    if c in TRADE:
        return {"类目": "交易状态", "链": "", "环节": "", "主题域": "", "子类": "交易状态", "规则": "交易状态表"}
    if c in EVENT:
        return {"类目": "事件财务", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "事件词表"}
    # 兜底规则（形态识别，能收一批长尾）
    if c.endswith("自贸区") or c.endswith("自贸"):
        return {"类目": "地域区域", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "后缀·自贸"}
    if c in GENERIC:
        return {"类目": "泛主题", "链": "", "环节": "", "主题域": "", "子类": "", "规则": "泛主题表"}
    return {"类目": "待归类", "链": "", "环节": "", "主题域": "", "子类": "", "规则": ""}


def collect_concepts():
    u = json.load(open(UNI, encoding="utf-8"))
    cnt = Counter()
    codes = {}
    for code, v in u.items():
        if code.startswith("_"):
            continue
        for t in (v.get("全部概念") or []):
            cnt[t] += 1
            codes.setdefault(t, []).append(v.get("name") or code)
    return u, cnt, codes


def build():
    u, cnt, codes = collect_concepts()
    mp = {t: classify(t) for t in cnt}
    json.dump(mp, open(OUT_MAP, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    by = Counter(v["类目"] for v in mp.values())
    inst_by = Counter()
    for t, n in cnt.items():
        inst_by[mp[t]["类目"]] += n
    total_t = len(cnt)
    total_i = sum(cnt.values())
    print(f"概念 {total_t} 个 / 票次 {total_i}")
    for k, n in by.most_common():
        print(f"  {k:6s} {n:4d} 个（{n/total_t*100:5.1f}%）｜票次 {inst_by[k]:6d}（{inst_by[k]/total_i*100:5.1f}%）")
    left = [t for t, v in mp.items() if v["类目"] == "待归类"]
    if left:
        print("\n待归类 %d 个：" % len(left), "、".join(left[:40]))
    return mp, cnt, codes


def export_csv(mp, cnt, codes, date="20261025"):
    u = json.load(open(UNI, encoding="utf-8"))
    outdir = os.path.join(ROOT, "reports", date, "全量库")
    os.makedirs(outdir, exist_ok=True)
    # 1) 概念归位总表
    p1 = os.path.join(outdir, "概念归位总表.csv")
    with open(p1, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["概念", "类目", "链", "环节", "主题域", "子类", "规则", "覆盖票数", "示例股"])
        for t, n in cnt.most_common():
            v = mp[t]
            w.writerow([t, v["类目"], v["链"], v["环节"], v["主题域"], v["子类"], v["规则"],
                        n, "、".join((codes.get(t) or [])[:5])])
    # 2) 链环节字典
    p2 = os.path.join(outdir, "链环节字典.csv")
    with open(p2, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["链", "环节", "环节词数", "环节词示例"])
        for cname, cv in CFG["chains"].items():
            if cname.startswith("_"):
                continue
